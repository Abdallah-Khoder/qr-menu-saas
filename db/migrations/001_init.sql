-- 001_init: the core tables of the platform.
--
-- Rules of the game:
--  * Every restaurant-owned table carries restaurant_id, so every query can (and must)
--    filter by it. That is what keeps one restaurant away from another one's data.
--  * Ids are random UUIDs, not 1, 2, 3...: nobody can guess a neighbour's id by counting.
--    (This is an extra layer. The ownership check on every query is still the real protection.)
--  * Prices are NUMERIC(12,2): exact decimals ("1.50" is stored as 1.50). Never FLOAT or DOUBLE,
--    which cannot represent most decimals exactly (0.1 + 0.2 = 0.30000000000000004).
--  * Secrets (passwords, invite tokens, email codes) are stored as hashes, never as-is.
--  * Names and descriptions are free text in any language: the owner types what he wants.
--  * Do not edit this file after it has been applied. Add a new numbered migration instead.

CREATE TABLE users (
  id                UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Stored in lowercase so "A@x.com" and "a@x.com" cannot be two accounts.
  email             TEXT        NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%_@_%'),
  password_hash     TEXT        NOT NULL,
  role              TEXT        NOT NULL CHECK (role IN ('super_admin', 'owner')),
  email_verified_at TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE restaurants (
  id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- UNIQUE = one restaurant per account (drop the UNIQUE later to allow several).
  -- Deleting the ACCOUNT deletes its restaurant. Deleting the RESTAURANT keeps the account.
  -- The application never gives a super admin a restaurant.
  owner_id     UUID        NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  name         TEXT        NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  -- Public link: /m/<public_slug>, e.g. shaarcrepe-k3x9qp7vtz
  -- = readable name (letters/digits/dashes) + dash + 10 random lowercase letters/digits.
  public_slug  TEXT        NOT NULL UNIQUE CHECK (
                 public_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*-[a-z0-9]{10}$' AND char_length(public_slug) <= 60),
  status       TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  -- Which prices the menu shows: dollars, Lebanese pounds, or both.
  currencies   TEXT        NOT NULL DEFAULT 'USD' CHECK (currencies IN ('USD', 'LBP', 'BOTH')),
  -- ONE number for the call button and the WhatsApp button, international format.
  phone_number TEXT        CHECK (phone_number ~ '^\+[1-9][0-9]{7,14}$'),
  map_url      TEXT        CHECK (map_url ~ '^https://'),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE invites (
  id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Hash of the random token inside the link. If the database leaks, the links stay unusable.
  token_hash TEXT        NOT NULL UNIQUE,
  -- Optional: restrict the invite to one email address.
  email      TEXT        CHECK (email = lower(email)),
  created_by UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  -- NULL until the sign-up is completed (email verified); then it can never be used again.
  used_at    TIMESTAMPTZ,
  used_by    UUID        REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE email_codes (
  id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- verify_email now; reset_password later, with no new table.
  purpose    TEXT        NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
  code_hash  TEXT        NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  -- Wrong guesses so far. The application invalidates the code after 5.
  attempts   INTEGER     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  -- Also used to limit how often a new code can be requested.
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX email_codes_lookup_idx ON email_codes (user_id, purpose, created_at DESC);

CREATE TABLE categories (
  id            UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id UUID    NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  name          TEXT    NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  sort_order    INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  -- Lets child tables reference the PAIR (id, restaurant_id), see items below.
  UNIQUE (id, restaurant_id)
);
CREATE INDEX categories_menu_idx ON categories (restaurant_id, sort_order);

CREATE TABLE items (
  id            UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id UUID    NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  category_id   UUID    NOT NULL,
  name          TEXT    NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 80),
  description   TEXT    NOT NULL DEFAULT '' CHECK (char_length(description) <= 300),
  -- The item's own price, in each currency. Both NULL when the item has sizes
  -- (the sizes carry the prices). "Either own price(s) or at least 2 sizes", and "the
  -- currencies the restaurant chose must be filled", are checked by the application:
  -- SQL cannot express rules that span two tables with a simple CHECK.
  -- NUMERIC has a special value 'NaN' ("not a number") that PostgreSQL considers BIGGER than
  -- every number, so ">= 0" alone would let it through. We refuse it explicitly.
  price_usd     NUMERIC(12,2) CHECK (price_usd >= 0 AND price_usd <> 'NaN'),
  price_lbp     NUMERIC(12,2) CHECK (price_lbp >= 0 AND price_lbp <> 'NaN'),
  image_url     TEXT    CHECK (image_url ~ '^https://'),
  sort_order    INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  -- The category must belong to the SAME restaurant as the item. The database itself
  -- refuses an item that points to another restaurant's category.
  FOREIGN KEY (category_id, restaurant_id)
    REFERENCES categories (id, restaurant_id) ON DELETE CASCADE,
  UNIQUE (id, restaurant_id)
);
CREATE INDEX items_category_idx ON items (category_id, sort_order);

CREATE TABLE item_sizes (
  id            UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id UUID    NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  item_id       UUID    NOT NULL,
  -- Short, chosen by the owner: S, M, L, XL, XXL...
  label         TEXT    NOT NULL CHECK (label ~ '^[A-Za-z0-9]{1,6}$'),
  price_usd     NUMERIC(12,2) CHECK (price_usd >= 0 AND price_usd <> 'NaN'),
  price_lbp     NUMERIC(12,2) CHECK (price_lbp >= 0 AND price_lbp <> 'NaN'),
  sort_order    INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  -- A size without any price makes no sense.
  CONSTRAINT size_has_a_price CHECK (price_usd IS NOT NULL OR price_lbp IS NOT NULL),
  FOREIGN KEY (item_id, restaurant_id)
    REFERENCES items (id, restaurant_id) ON DELETE CASCADE,
  UNIQUE (item_id, label)
);
